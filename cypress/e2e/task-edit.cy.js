describe('Тестирование формы редактирования задачи и СППР', () => {
  
  beforeEach(() => {
    // 1. Переходим на страницу логина
    cy.visit('/login') // Укажи свой точный путь к странице авторизации, если он отличается

    // 2. Находим поля ввода логина/пароля и вводим данные user3 / user3
    // Замени селекторы 'input[type="text"]' и 'input[type="password"]', если у тебя другие
    cy.get('input[placeholder*="Логин"]').type('user3')
    cy.get('input[placeholder*="Пароль"]').type('user3')

    // 3. Нажимаем кнопку Войти
    cy.contains('button', 'Войти').click()

    // 4. Проверяем, что авторизация прошла успешно (например, нас редиректнуло или появился токен)
    cy.url().should('not.include', '/login')

    // 5. И только после успешного входа переходим на страницу редактирования задачи
    
  })

  it('При успешном входе должен открываться главный дашборд', () => {
    // Переходим на корень сайта
    cy.visit('/') 
    
    // Проверяем наличие ключевых элементов дашборда (заголовок, графики или статистика)
    cy.contains('Дашборд').should('be.visible')
    // Либо по твоему названию, например: cy.contains('Панель управления').should('be.visible')
  })

  // Тест 2: Переход в список задач через меню
  it('При нажатии на пункт меню "Задачи" должен открываться список задач', () => {
    cy.visit('/')

    // Находим в боковом или верхнем меню пункт "Задачи" и кликаем
    cy.get('nav').contains('Задачи').click()

    // Проверяем, что URL изменился на список задач
    cy.url().should('include', '/tasks')
    
    // Проверяем, что на странице появилась таблица или список
    cy.contains('Мои задачи').should('be.visible')
  })

  it('Должен успешно загрузить форму и отобразить текущие навыки', () => {
    cy.visit('/tasks/edit/3')
    cy.get('input[placeholder*="например: Дизайн адаптивного лендинга"]').should('be.visible')
    cy.contains('Теги / Метки задачи').should('be.visible')
  })


  it('Должен отправить форму и обновить задачу', () => {
    cy.visit('/tasks/edit/3')
    cy.get('textarea').clear().type('Обновленное ТЗ для разработчиков. Проверить интеграцию с Jira.')
    cy.contains('button', 'Сохранить').click()
  })

  
})